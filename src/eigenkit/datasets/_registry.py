"""
Central metadata registry for all available datasets in eigenkit.
"""

from typing import Literal, Optional

from pydantic import BaseModel, Field


class DatasetInfo(BaseModel):
    """The metadata of a dataset that eigenkit provides.

    Args:
        name (str): The unique name of the dataset, which is also its key in
            `REGISTRY`.
        source (str): Where the dataset comes from. It is one of these values:

            - `'sklearn'`: the dataset is loaded with a function of
              `sklearn.datasets`.
            - `'url'`: the dataset is downloaded from a web address.
            - `'synthetic'`: the dataset is generated by a function, for example
              `make_moons`.

        url (str, optional): The web address of the file to download. It is used
            only when `source='url'`.
        sha256 (str, optional): The SHA-256 hash, in hexadecimal, that the
            downloaded file must match. A downloaded file that does not match is
            deleted, and a `ValueError` is raised. A cached file that does not match
            is downloaded again. It is used only when `source='url'`.
        sklearn_loader (str, optional): The name of the `sklearn.datasets` function,
            for example `'load_iris'`. It is used only when `source='sklearn'`.
        synthetic_generator (str, optional): The name of the generator function, for
            example `'make_moons'`. It is used only when `source='synthetic'`.
        task (str): The type of task: `'classification'`, `'regression'`,
            `'timeseries'`, `'optimization'` or `'chemistry'`.
        n_features (int): The number of input features. It must be at least `1`.
        n_samples (int, optional): The total number of samples. It is `None` when
            the number is not recorded, for example for the synthetic datasets,
            whose size is chosen when they are generated.
        n_classes (int, optional): The number of classes. It is `None` for
            regression and time-series tasks.
        feature_names (list[str], optional): Readable names of the input features.
        target_names (list[str], optional): Readable names of the classes, or of the
            output.
        window_size (int, optional): The recommended size of the sliding window, for
            time-series datasets.
        description (str): A short description of the dataset.

    Example:
        ```python
        info = DatasetInfo(
            name="iris",
            source="sklearn",
            sklearn_loader="load_iris",
            task="classification",
            n_features=4,
            n_samples=150,
            n_classes=3,
            description="Classic multi-class classification dataset.",
        )
        ```
    """

    name: str
    source: Literal["sklearn", "url", "synthetic"]
    url: Optional[str] = None
    sha256: Optional[str] = None
    sklearn_loader: Optional[str] = None
    synthetic_generator: Optional[str] = None
    task: Literal[
        "classification", "regression", "timeseries", "optimization", "chemistry"
    ]
    n_features: int = Field(..., ge=1)
    n_samples: Optional[int] = Field(default=None, gt=0)
    n_classes: Optional[int] = Field(default=None, gt=0)
    feature_names: Optional[list[str]] = None
    target_names: Optional[list[str]] = None
    window_size: Optional[int] = Field(default=None, gt=0)
    description: str

    def __init__(
        self,
        name: str,
        source: Literal["sklearn", "url", "synthetic"],
        task: Literal[
            "classification", "regression", "timeseries", "optimization", "chemistry"
        ],
        n_features: int,
        description: str,
        url: Optional[str] = None,
        sha256: Optional[str] = None,
        sklearn_loader: Optional[str] = None,
        synthetic_generator: Optional[str] = None,
        n_samples: Optional[int] = None,
        n_classes: Optional[int] = None,
        feature_names: Optional[list[str]] = None,
        target_names: Optional[list[str]] = None,
        window_size: Optional[int] = None,
    ):
        super().__init__(
            name=name,
            source=source,
            url=url,
            sha256=sha256,
            sklearn_loader=sklearn_loader,
            synthetic_generator=synthetic_generator,
            task=task,
            n_features=n_features,
            n_samples=n_samples,
            n_classes=n_classes,
            feature_names=feature_names,
            target_names=target_names,
            window_size=window_size,
            description=description,
        )


