def get_dataset_info(name: str) -> DatasetInfo:
    """Return the `DatasetInfo` of a dataset.

    Args:
        name (str): The key of the dataset in `REGISTRY`.

    Returns:
        The metadata of the dataset.

    Raises:
        ValueError: If `name` is not in the registry. The message lists every
            available name.

    Example:
        ```python
        info = get_dataset_info("iris")
        ```
    """
    if name not in REGISTRY:
        available = ", ".join(sorted(REGISTRY.keys()))
        raise ValueError(
            f"Dataset '{name}' not found in registry. Available datasets: {available}"
        )
    return REGISTRY[name]
